"""Generate compact 1-bit subtitle fonts; requires Pillow and fonttools.

Usage: python generate.py /path/to/NotoSansHebrew.ttf
Source: google/fonts ofl/notosanshebrew/NotoSansHebrew[wdth,wght].ttf
Font license: OFL.txt. Generated bitmaps retain that license.
"""
import hashlib
import pathlib
import sys

from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

source = pathlib.Path(sys.argv[1])
dest = pathlib.Path(__file__).parent
cmap = TTFont(source).getBestCmap()
candidates = list(range(0x20, 0x100)) + list(range(0x5D0, 0x5F5))
candidates += [0x5BE, 0x5C0, 0x5C3, 0x5C6, 0x20AA]
candidates += list(range(0x2010, 0x2027))
codepoints = sorted(c for c in set(candidates) if c in cmap)
assert all(c in codepoints for c in range(0x5D0, 0x5EB))
ranges = []
for i, c in enumerate(codepoints):
    if ranges and ranges[-1][1] + 1 == c:
        ranges[-1][1] = c
    else:
        ranges.append([c, c, i])

lines = ['// Generated by generate.py; font bitmaps licensed under OFL-1.1 (OFL.txt).',
         '// Noto Sans Hebrew source SHA-256: ' + hashlib.sha256(source.read_bytes()).hexdigest(),
         '#include "hebrew_font.hpp"', '',
         'namespace stackchan::avatar::internal {', 'namespace {']
for size in (12, 24):
    font = ImageFont.truetype(str(source), size, layout_engine=ImageFont.Layout.BASIC)
    # The source variable font defaults to weight 100 (Thin), whose small
    # punctuation disappears after 1-bit quantization. Use a readable Medium.
    font.set_variation_by_axes([500, 100])
    data, glyphs = [], []
    for c in codepoints:
        char = chr(c)
        x0, y0, x1, y1 = font.getbbox(char, anchor='ls')
        w, h = x1 - x0, y1 - y0
        image = Image.new('L', (max(1, w), max(1, h)))
        ImageDraw.Draw(image).text((-x0, -y0), char, font=font, fill=255, anchor='ls')
        bits = [int(image.getpixel((x, y)) >= 96) for y in range(h) for x in range(w)]
        glyphs.append((len(data), w, h, round(font.getlength(char)), x0, y0))
        for offset in range(0, len(bits), 8):
            data.append(sum(b << (7 - j) for j, b in enumerate(bits[offset:offset + 8])))
    lines += [f'const std::uint8_t bitmap_{size}[] = {{']
    lines += ['    ' + ', '.join(f'0x{v:02x}' for v in data[i:i+20]) + ',' for i in range(0, len(data), 20)]
    lines += ['};', f'const lgfx::GFXglyph glyphs_{size}[] = {{']
    lines += ['    {' + ', '.join(str(v) for v in g) + '}, // U+' + f'{c:04X}' for c, g in zip(codepoints, glyphs)]
    lines += ['};']
lines += ['const lgfx::EncodeRange ranges[] = {']
lines += [f'    {{0x{a:04x}, 0x{b:04x}, {i}}},' for a, b, i in ranges]
lines += ['};', '} // namespace']
for size in (12, 24):
    lines += [f'const lgfx::GFXfont hebrew_font_{size}(',
              f'    const_cast<std::uint8_t*>(bitmap_{size}), const_cast<lgfx::GFXglyph*>(glyphs_{size}),',
              f'    0x{codepoints[0]:04x}, 0x{codepoints[-1]:04x}, {size},',
              '    sizeof(ranges) / sizeof(ranges[0]), const_cast<lgfx::EncodeRange*>(ranges));']
lines += ['} // namespace stackchan::avatar::internal', '']
output = dest / 'hebrew_font.cpp'
if output.exists():
    print('Regenerating existing generated font:', output)
output.write_text('\n'.join(lines), encoding='utf-8')
print('Generated', len(codepoints), 'glyphs per size;', len(ranges), 'Unicode ranges')
